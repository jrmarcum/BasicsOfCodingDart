// Dart has various value types. Here are some basic types available:
// String, int, double, bool, and more.

void main() {
  // Strings, which can be added together with `+`.
  print('dart' + 'lang');

  // Integers and floats.
  print('1+1 = ${1 + 1}');
  print('7.0/3.0 = ${7.0 / 3.0}');

  // Booleans, with boolean operators as you'd expect.
  print(true && false);
  print(true || false);
  print(!true);
}
